-- Character requests. A character's owner can't name someone as its player; they ask, by email address, and the person
-- becomes the player only by accepting. A character has at most one request at a time: pending until it is answered,
-- or kept as DENIED (so the owner sees it was turned down, and can't ask the same address again at once) until the
-- owner dismisses it or asks someone else. An accepted request is deleted: played_by on the character is the record.

CREATE TABLE open5e.character_requests (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY,
    player_id    bigint      NOT NULL,
    requested_by bigint      NOT NULL,
    email        text        NOT NULL,
    status       text        NOT NULL DEFAULT 'PENDING',
    created_at   timestamptz NOT NULL DEFAULT now(),
    expires_at   timestamptz NOT NULL,
    responded_at timestamptz,
    CONSTRAINT character_requests_pkey PRIMARY KEY (id),
    CONSTRAINT character_requests_status_check CHECK (status IN ('PENDING', 'DENIED')),
    CONSTRAINT character_requests_player_id_key UNIQUE (player_id),
    CONSTRAINT character_requests_player_id_fk FOREIGN KEY (player_id) REFERENCES open5e.player_characters (id) ON DELETE CASCADE,
    CONSTRAINT character_requests_requested_by_fk FOREIGN KEY (requested_by) REFERENCES open5e.users (id) ON DELETE CASCADE
);

CREATE INDEX character_requests_email_idx ON open5e.character_requests (email);
CREATE INDEX character_requests_requested_by_idx ON open5e.character_requests (requested_by);
